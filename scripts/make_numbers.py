"""Write outputs/numbers.tex: every summary statistic as a LaTeX macro, so no number has to be typed by hand.
  \\R{dataset|method|k|metric}      mean over draws (1 decimal)
  \\Rs{dataset|method|k|metric}     std over draws
  \\Rp{dataset|method|k|metric}     10th percentile over draws
  \\Pv{dataset|other|k|metric}      Holm-corrected p (VMF vs other), 3 decimals or '<0.001'
  \\Dm{dataset|other|k|metric}      mean paired difference VMF - other (signed, 1 decimal)
Undefined keys render as '??' so missing numbers are visible in the PDF."""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
S = pd.read_csv(ROOT / "results" / "summary.csv")
T = pd.read_csv(ROOT / "results" / "tests.csv")
out = [r"% generated by scripts/make_numbers.py from results/summary.csv and results/tests.csv -- do not edit",
       r"\makeatletter",
       r"\def\R#1{\@ifundefined{r@#1}{??}{\csname r@#1\endcsname}}",
       r"\def\Rs#1{\@ifundefined{rs@#1}{??}{\csname rs@#1\endcsname}}",
       r"\def\Rp#1{\@ifundefined{rp@#1}{??}{\csname rp@#1\endcsname}}",
       r"\def\Pv#1{\@ifundefined{pv@#1}{??}{\csname pv@#1\endcsname}}",
       r"\def\Dm#1{\@ifundefined{dm@#1}{??}{\csname dm@#1\endcsname}}"]
for _, r in S.iterrows():
    key = f"{r.dataset}|{r.method}|{int(r.k)}|{r.metric}"
    out.append(rf"\expandafter\def\csname r@{key}\endcsname{{{r['mean']:.1f}}}")
    if pd.notna(r["std"]):
        out.append(rf"\expandafter\def\csname rs@{key}\endcsname{{{r['std']:.1f}}}")
    out.append(rf"\expandafter\def\csname rp@{key}\endcsname{{{r['p10']:.1f}}}")
for _, r in T.iterrows():
    key = f"{r.dataset}|{r.other}|{int(r.k)}|{r.metric}"
    p = r["p_holm"]
    ps = "<0.001" if p < 0.001 else f"{p:.3f}"
    out.append(rf"\expandafter\def\csname pv@{key}\endcsname{{{ps}}}")
    out.append(rf"\expandafter\def\csname dm@{key}\endcsname{{{r['mean_diff']:+.1f}}}")
out.append(r"\makeatother")
(ROOT / "outputs" / "numbers.tex").write_text("\n".join(out) + "\n")
print("macros:", len(out))
